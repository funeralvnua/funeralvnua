import type { Metadata } from 'next';
import { setRequestLocale, getTranslations } from 'next-intl/server';
import { routing, type Locale } from '@/i18n/routing';
import { Breadcrumbs } from '@/components/seo/Breadcrumbs';
import { buildUrl } from '@/lib/utils';

export function generateStaticParams() {
  return routing.locales.map((locale) => ({ locale }));
}

export async function generateMetadata({
  params,
}: {
  params: Promise<{ locale: string }>;
}): Promise<Metadata> {
  const { locale } = await params;
  const isUk = locale === 'uk';
  return {
    title: isUk ? 'Політика конфіденційності' : 'Политика конфиденциальности',
    description: isUk
      ? 'Як ми обробляємо персональні дані відвідувачів сайту згідно з ЗУ «Про захист персональних даних».'
      : 'Как мы обрабатываем персональные данные посетителей сайта согласно ЗУ «О защите персональных данных».',
    alternates: {
      canonical: buildUrl('polityka-konfidentsiynosti', locale as Locale),
      languages: {
        'uk-UA': buildUrl('polityka-konfidentsiynosti', 'uk'),
        'ru-UA': buildUrl('polityka-konfidentsiynosti', 'ru'),
        'x-default': buildUrl('polityka-konfidentsiynosti', 'uk'),
      },
    },
    robots: { index: false, follow: true },
  };
}

export default async function PrivacyPage({
  params,
}: {
  params: Promise<{ locale: string }>;
}) {
  const { locale } = await params;
  setRequestLocale(locale);
  const tNav = await getTranslations('nav');
  const tFooter = await getTranslations('footer');
  const isUk = locale === 'uk';

  return (
    <>
      <section className="hero-gradient">
        <div className="container-content py-10 md:py-14">
          <Breadcrumbs
            items={[
              { label: tNav('home'), href: '/' },
              { label: tFooter('privacy'), href: '/polityka-konfidentsiynosti/' },
            ]}
          />
          <h1 className="mt-6">{tFooter('privacy')}</h1>
          <div className="divider-gold mt-6 max-w-[80px]" />
        </div>
      </section>

      <section className="container-content py-10 md:py-16">
        <div className="prose-mdx max-w-3xl">
          {isUk ? <PrivacyUk /> : <PrivacyRu />}
        </div>
      </section>
    </>
  );
}

