import type { Metadata } from 'next';
import { setRequestLocale, getTranslations } from 'next-intl/server';
import { routing, type Locale } from '@/i18n/routing';
import { Breadcrumbs } from '@/components/seo/Breadcrumbs';
import { buildUrl } from '@/lib/utils';

export function generateStaticParams() {
  return routing.locales.map((locale) => ({ locale }));
}

export async function generateMetadata({
  params,
}: {
  params: Promise<{ locale: string }>;
}): Promise<Metadata> {
  const { locale } = await params;
  const isUk = locale === 'uk';
  return {
    title: isUk ? 'Публічна оферта' : 'Публичная оферта',
    description: isUk
      ? 'Умови надання ритуальних послуг Вінницькою міською ритуальною службою.'
      : 'Условия оказания ритуальных услуг Винницкой городской ритуальной службой.',
    alternates: {
      canonical: buildUrl('oferta', locale as Locale),
      languages: {
        'uk-UA': buildUrl('oferta', 'uk'),
        'ru-UA': buildUrl('oferta', 'ru'),
        'x-default': buildUrl('oferta', 'uk'),
      },
    },
    robots: { index: false, follow: true },
  };
}

export default async function OfferPage({
  params,
}: {
  params: Promise<{ locale: string }>;
}) {
  const { locale } = await params;
  setRequestLocale(locale);
  const tNav = await getTranslations('nav');
  const tFooter = await getTranslations('footer');
  const isUk = locale === 'uk';

  return (
    <>
      <section className="hero-gradient">
        <div className="container-content py-10 md:py-14">
          <Breadcrumbs
            items={[
              { label: tNav('home'), href: '/' },
              { label: tFooter('offer'), href: '/oferta/' },
            ]}
          />
          <h1 className="mt-6">{tFooter('offer')}</h1>
          <div className="divider-gold mt-6 max-w-[80px]" />
        </div>
      </section>

      <section className="container-content py-10 md:py-16">
        <div className="prose-mdx max-w-3xl">
          {isUk ? <OfferUk /> : <OfferRu />}
        </div>
      </section>
    </>
  );
}

